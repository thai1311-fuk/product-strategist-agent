"""Экономика вариантов B (сигнал организатору) и D (предупреждение владельцу своих номеров).
Запуск: python3 -I projects/family-connect/data/econ.py > projects/family-connect/data/econ.md
v2 (после возражений critic): реальный календарь, эффект только на «свою» часть оттока,
каннибализация докупки, полная стоимость вложений, окупаемость и граница решения.
Все параметры, кроме ставки 500 руб. и чисел брифа, — ДОПУЩЕНИЯ (E057, E058, E065).
"""

RATE = 500                 # руб. валовой прибыли за доп. оплаченный месяц номера [E011]
TARGET_GAP = 6_000_000     # 285 - 279 млн руб. [E003]
GROUPS = 8_000             # подключённых групп «без изменений» [E005]
PILOT_GROUPS = 1_200       # пилотная ветка (контроль — ещё 1 200, без услуги) [E063]
import sys as _sys
# Календарь можно передать аргументами: econ.py [месяц старта пилота] [месяц раскатки] — для проверки чувствительности.
PILOT_START = int(_sys.argv[1]) if len(_sys.argv) > 1 else 6     # июнь: разработка в Q2 (апрель–май) [E012]
ROLLOUT_START = int(_sys.argv[2]) if len(_sys.argv) > 2 else 10  # октябрь: по клиентскому результату пилота
HOLDOUT = 0.10             # 10 % подходящих групп остаются группой сравнения при раскатке
PM_COST = (0.4e6, 0.6e6)   # руб. за человеко-месяц [E058]
INVEST_PM = 3 + 1 + 1.5 + 1.5  # разработка 3, тестирование 1, дизайнер и аналитик по 0,5 ставки на 3 мес.

# Сценарии B: (номеров в группе, отток номера в мес. без услуги, доля оттока, связанного с перебоями
#   по исчерпанию доли, доля подходящих групп (тариф+согласие), доля организаторов, которые реагируют,
#   доля докупок участниками, заменённых бесплатной передачей)
B = {
    "слабый":   (2.5, 0.015, 0.10, 0.60, 0.50, 0.50),
    "основной": (2.8, 0.020, 0.15, 0.70, 0.60, 0.40),
    "сильный":  (3.2, 0.025, 0.25, 0.80, 0.70, 0.30),
}
EVENTS_PER_GROUP_MONTH = 0.10   # подходящий случай у ~10 % групп в месяц [E062]
ADDON_SHARE = 0.20              # в 20 % случаев участник сейчас докупает пакет сам [E065]
ADDON_GP = 100                  # руб. валовой прибыли с докупки [E065]


def n(x):
    return f"{x:,.0f}".replace(",", " ")


def surv_diff(numbers, c0, r, k):
    c1 = c0 * (1 - r)
    return numbers * ((1 - c1) ** k - (1 - c0) ** k)


def months_in_year(numbers, c0, r, start, last=12):
    """Доп. оплаченные месяцы для когорты, получившей услугу в месяце `start`, по месяц `last` включительно."""
    return sum(surv_diff(numbers, c0, r, k) for k in range(1, last - start + 2)) if last >= start else 0.0


def scenario(per_group, c0, s, elig, react, cannib):
    r = s * react  # снижение оттока у групп, получивших услугу
    eligible = GROUPS * elig
    pilot_nums = PILOT_GROUPS * per_group
    roll_nums = max(0.0, eligible * (1 - HOLDOUT) - PILOT_GROUPS) * per_group

    def gp_upto(m):
        a = months_in_year(pilot_nums, c0, r, PILOT_START, m)
        b = months_in_year(roll_nums, c0, r, ROLLOUT_START, m)
        # каннибализация: события у групп с услугой × доля докупок × замещение × прибыль с докупки
        groups_on = lambda mm: (PILOT_GROUPS if mm >= PILOT_START else 0) + (roll_nums / per_group if mm >= ROLLOUT_START else 0)
        lost = sum(groups_on(mm) * EVENTS_PER_GROUP_MONTH * ADDON_SHARE * cannib * ADDON_GP for mm in range(1, m + 1))
        return (a + b) * RATE - lost, a + b, lost
    return r, gp_upto


out = []
p = out.append
p("# Экономика вариантов B и D (v2, после возражений critic)\n")
p("Из брифа: 500 руб. за доп. оплаченный месяц [E011], разрыв 6 млн руб. [E003], 8 000 групп [E005], 3 человеко-месяца разработки на Q2 [E012]. "
  "Остальное — допущения [E057], [E058], [E065].\n")
p(f"Календарь: Q1 — диагностика; апрель–май — разработка; пилот на {PILOT_GROUPS} группах (+{PILOT_GROUPS} в группе сравнения) с месяца {PILOT_START}; "
  f"раскатка на подходящие группы с месяца {ROLLOUT_START}, {HOLDOUT:.0%} остаются группой сравнения.\n")
p("Снижение оттока r = доля оттока, связанного с перебоями по исчерпанию доли × доля организаторов, которые реагируют на сигнал.\n")
p("| Сценарий | r | Доп. месяцев в плановом году | Валовая прибыль от доп. месяцев, млн руб. | Каннибализация, млн руб. | Вклад в плановом году, млн руб. | Накоплено за 8 кварталов, млн руб. | Окупаемость вложений 2,8–4,2 млн |")
p("|---|---|---|---|---|---|---|---|")
invest_lo, invest_hi = INVEST_PM * PM_COST[0], INVEST_PM * PM_COST[1]
results = {}
for name, params in B.items():
    r, gp_upto = scenario(*params)
    gp12, m12, lost12 = gp_upto(12)
    gp24, _, _ = gp_upto(24)
    q_pay = None
    for q in range(1, 13):
        if gp_upto(q * 3)[0] >= invest_lo:
            q_pay = q
            break
    pay = f"при 2,8 млн — квартал {q_pay} от начала планового года" if q_pay else "не окупается за 3 года"
    results[name] = (r, gp12, gp24)
    p(f"| {name} | {r:.1%} | {n(m12)} | {m12 * RATE / 1e6:.2f} | {lost12 / 1e6:.2f} | {gp12 / 1e6:.2f} | {gp24 / 1e6:.2f} | {pay} |")
p("")
p(f"Вложения: {INVEST_PM} человеко-месяца (разработка 3, тестирование 1, дизайнер и аналитик по 0,5 ставки на 3 мес.) × 0,4–0,6 млн руб. = "
  f"{invest_lo / 1e6:.1f}–{invest_hi / 1e6:.1f} млн руб. [E058]. Прямые расходы на push-уведомления в собственном приложении приняты нулевыми.\n")

r_base, gp12_base, gp24_base = results["основной"]
p("## Граница решения\n")
p(f"- ИТОГ B: в основном сценарии вклад в плановом году {gp12_base / 1e6:.2f} млн руб.; за 8 кварталов {gp24_base / 1e6:.2f} млн руб. — меньше вложений 2,8–4,2 млн.")
# Какое r нужно для окупаемости 2,8 млн за 8 кварталов (основные прочие параметры)
per_group, c0, s, elig, react, cannib = B["основной"]
lo, hi = 0.0, 1.0
for _ in range(50):
    mid = (lo + hi) / 2
    _, f = scenario(per_group, c0, mid, elig, 1.0, cannib)
    lo, hi = (mid, hi) if f(24)[0] < invest_lo else (lo, mid)
p(f"- Порог окупаемости за 8 кварталов (вложения 2,8 млн): нужно снижение оттока у групп с услугой r ≥ {hi:.1%} "
  f"(например, перебои по исчерпанию дают {hi / 0.6:.0%} оттока при реакции 60 % организаторов).")
_, f_full = scenario(per_group, c0, 1.0, elig, 1.0, cannib)
p(f"- Даже при полной остановке оттока у групп с услугой (r = 100 %) плановый год даёт {f_full(12)[0] / 1e6:.2f} млн руб.")
p(f"- ИТОГ: цель +6 млн руб. в плановом году этой услугой недостижима; нужно {n(TARGET_GAP / RATE)} доп. месяцев.")
p("- Формула вклада: 500 × Σ_k N × [(1 − c0·(1 − r))^k − (1 − c0)^k] − каннибализация; N — номера с услугой, c0 — отток без услуги, r — снижение оттока, k — месяцы после старта.\n")

# Что нужно, чтобы закрыть разрыв привлечением новых номеров
p("## Разрыв 6 млн руб. другим путём: новые номера через приглашение в группу\n")
for start in (4, 7):
    months = 12 - start + 1
    need = TARGET_GAP / RATE / (months / 2 + 0.5)  # равномерный набор с месяца start: в среднем (months+1)/2 оплаченных месяцев
    p(f"- Если приглашённые близкие переходят от других операторов равномерно с месяца {start}: нужно ≈ {n(need)} новых номеров к концу года "
      f"(в среднем {(months + 1) / 2:.1f} оплаченных месяца на номер).")
p("- ИТОГ: закрыть разрыв по прибыли в плановом году можно только привлечением новых платящих номеров (тысячи номеров), а не удержанием; это отдельное решение руководителя.\n")

# Вариант D
p("## Вариант D: предупреждение владельцу своих номеров (для сравнения)\n")
owners, nums, c0d = 1_000, 3.0, 0.025
for name, (s_d, react_d) in {"слабый": (0.15, 0.5), "основной": (0.30, 0.6), "сильный": (0.45, 0.7)}.items():
    r_d = s_d * react_d
    m_y1 = months_in_year(owners * nums, c0d, r_d, ROLLOUT_START, 12)
    m_y2 = sum(surv_diff(owners * nums, c0d, r_d, k) for k in range(1, 13))
    p(f"- {name}: r = {r_d:.0%}; с октября планового года {m_y1 * RATE / 1e6:.2f} млн руб.; за первые 12 месяцев работы {m_y2 * RATE / 1e6:.2f} млн руб.")
p("- ИТОГ D: на 1 000 подключённых владельцах (3 номера, отток 2,5 %/мес., доля оттока из-за остановки по неоплате 15–45 %) эффект на номер выше, чем у B, но база в 8 раз меньше; в плановом году вклад меньше 0,1 млн руб.")

print("\n".join(out))
